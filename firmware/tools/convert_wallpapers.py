"""Convert numbered watch PNGs into one LVGL 9 translation unit."""

import argparse
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile


WIDTH, HEIGHT = 390, 450
PNG_HEADER = b"\x89PNG\r\n\x1a\n\x00\x00\x00\x0dIHDR"
SLOTS = tuple(f"wallpaper_{index:02d}" for index in range(1, 6))
DEFAULT_INPUT = Path(__file__).resolve().parents[1] / "assets" / "wallpapers"


def load_assets(directory):
    images = sorted(directory.glob("*.png"))
    if not 2 <= len(images) <= len(SLOTS):
        raise ValueError(f"{directory}: expected 2 to 5 PNG wallpapers")
    expected = [f"{slot}.png" for slot in SLOTS[:len(images)]]
    if [image.name for image in images] != expected:
        raise ValueError(f"{directory}: expected consecutive image names {', '.join(expected)}")

    for image in images:
        with image.open("rb") as stream:
            header = stream.read(24)
        if len(header) != 24 or not header.startswith(PNG_HEADER):
            raise ValueError(f"{image}: invalid PNG header")
        width, height = struct.unpack(">II", header[16:24])
        if (width, height) != (WIDTH, HEIGHT):
            raise ValueError(f"{image}: expected {WIDTH}x{HEIGHT}, got {width}x{height}")

    metadata = directory / "wallpapers.json"
    names = json.loads(metadata.read_text(encoding="utf-8-sig")) if metadata.is_file() else {}
    if not isinstance(names, dict) or any(
        key not in SLOTS or not isinstance(name, str) or not name.strip()
        or any(not char.isprintable() for char in name)
        for key, name in names.items()
    ):
        raise ValueError(f"{metadata}: expected an object mapping wallpaper slots to display names")
    return images, names


def converted_source(tool, image, work):
    result = subprocess.run(
        [str(tool), "-convert", str(image), "-rgb565", "-cfile", "2",
         "-lvgl_version", "9", "-chip", "sf52x", "-outdir", str(work)],
        cwd=work, capture_output=True,
    )
    output = work / f"{image.stem}.c"
    if result.returncode or not output.is_file():
        log = (result.stdout + result.stderr).decode(errors="replace").strip()
        raise ValueError(f"{image}: EZIP converter failed (exit code {result.returncode})\n{log}")

    source = output.read_text(encoding="utf-8-sig")
    size = re.search(r"\.data_size\s*=\s*(\d+)\b", source)
    if (
        not re.search(rf"\blv_(?:image|img)_dsc_t\s+{image.stem}\s", source)
        or not re.search(r"\.header\.magic\s*=\s*(?:0x19|LV_IMAGE_HEADER_MAGIC)\b", source)
        or not re.search(r"\.header\.flags\s*=\s*LV_IMAGE_FLAGS_(?:USER1|EZIP)\b", source)
        or not size or int(size[1]) == 0
    ):
        raise ValueError(f"{image}: converter did not produce an LVGL 9 EZIP descriptor")
    print(f"  {image.name}: {int(size[1]):,} EZIP bytes")
    return source, int(size[1])


def generate(directory, tool, output):
    images, names = load_assets(directory)
    output.parent.mkdir(parents=True, exist_ok=True)
    total = 0
    with tempfile.TemporaryDirectory(prefix="ezip-", dir=output.parent) as temp:
        work = Path(temp)
        generated = work / "wallpapers.c"
        with generated.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write('/* Generated by convert_wallpapers.py. */\n#include "watch_wallpapers.h"\n\n')
            for image in images:
                source, size = converted_source(tool, image, work)
                stream.write(source)
                stream.write("\n")
                total += size

            stream.write("\nconst lv_img_dsc_t *g_wallpapers[] = {\n")
            for image in images:
                stream.write(f"    &{image.stem},\n")
            stream.write("};\n\nconst char *const g_wallpaper_names[] = {\n")
            for image in images:
                name = names.get(image.stem)
                literal = json.dumps(name, ensure_ascii=False) if name is not None else "NULL"
                stream.write(f"    {literal},\n")
            stream.write("};\n\nconst unsigned g_wallpaper_count = sizeof(g_wallpapers) / sizeof(g_wallpapers[0]);\n")
        generated.replace(output)
    print(f"Wallpaper total: {total:,} EZIP bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="folder of numbered PNGs")
    parser.add_argument("--out", type=Path, required=True, help="generated C file")
    converter = parser.add_mutually_exclusive_group()
    converter.add_argument("--sdk-root", type=Path, help="SiFli SDK root (defaults to SIFLI_SDK)")
    converter.add_argument("--ezip", type=Path, help="specific SDK EZIP executable")
    args = parser.parse_args()

    tool = args.ezip
    if tool is None:
        sdk_root = args.sdk_root or os.environ.get("SIFLI_SDK")
        if not sdk_root:
            parser.error("set SIFLI_SDK or pass --sdk-root")
        exe = {"win32": "ezip.exe", "darwin": "ezip_mac", "linux": "ezip_linux"}.get(sys.platform)
        if exe is None:
            parser.error("pass --ezip for this host platform")
        tool = Path(sdk_root) / "tools" / "png2ezip" / exe
    try:
        generate(args.input.resolve(), tool.resolve(), args.out.resolve())
    except (OSError, ValueError) as error:
        print(f"Wallpaper conversion failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
